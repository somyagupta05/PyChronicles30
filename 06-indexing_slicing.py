# slicing
product="laptop pro 2024"
print(product[0:6])  # first 6 letters
print(product[-4:]) # last 4 letters

# skip test
print("skip text",product[0:12:2])

# reverse
print("reverse string",product[::-1])
# reverse first 4 char
print("reverse string",product[4::-1])

